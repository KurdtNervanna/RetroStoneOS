#!/bin/sh
# update-credits.sh: frontend/assets/credits.txt (Settings > System
# information > Credits) from the git history of this repository and of the
# RetroStone VC checkout next to it (../RetroStoneVC, the built-in games).
# Names only (no e-mail addresses), the most commits first. Run it from
# anywhere before a release and commit the result: Buildroot copies the
# sources without .git, so the build cannot ask git itself.
#
#   scripts/support/update-credits.sh [RetroStoneVC checkout]
set -eu

REPO=$(cd "$(dirname "$0")/../.." && pwd)
VC=${1:-$REPO/../RetroStoneVC}
OUT=$REPO/frontend/assets/credits.txt

authors() { # <repo>: one name per line, the most commits first
	git -C "$1" log --format='%aN' HEAD | sort | uniq -c | sort -k1,1nr -k2 | sed 's/^ *[0-9]* //'
}

{
	echo "# RetroStoneOS credits, shown in Settings > System information > Credits."
	echo "# Generated by scripts/support/update-credits.sh from the git history:"
	echo "# do not edit by hand. \"## \" lines are section titles."
	echo "## RetroStoneOS"
	authors "$REPO"
	if [ -d "$VC/.git" ] || [ -f "$VC/.git" ]; then
		echo "## RetroStone VC games"
		authors "$VC"
	fi
} > "$OUT.tmp"
mv "$OUT.tmp" "$OUT"
echo "update-credits.sh: $(grep -vc '^#' "$OUT") names in $OUT"
